/**
 * STAG i18n (beta.5) — tiny dependency-free dictionary layer.
 * Persian is the source of truth; English mirrors every key (a unit test
 * enforces key parity). `makeT` returns a lookup that interpolates {vars}.
 */

export type Lang = "fa" | "en";

export const LANG_KEY = "stag.lang.v1";
export const LANGS: Lang[] = ["fa", "en"];

export type TFn = (key: string, vars?: Record<string, string | number>) => string;

export function dirOf(lang: Lang): "rtl" | "ltr" {
  return lang === "fa" ? "rtl" : "ltr";
}

function interpolate(tpl: string, vars?: Record<string, string | number>): string {
  if (!vars) return tpl;
  return tpl.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

export function makeT(lang: Lang): TFn {
  const table = DICT[lang] ?? DICT.fa;
  return (key, vars) => {
    const v = table[key] ?? DICT.fa[key] ?? key;
    return interpolate(v, vars);
  };
}

